using System.Text;
using static AsyncEventBridge.Generators.GeneratorTypeSystem;
using static AsyncEventBridge.Generators.GeneratorSymbolAnalysis;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace AsyncEventBridge.Generators;

[Generator(LanguageNames.CSharp)]
public sealed class AsyncEventBridgeOccurrenceGenerator : IIncrementalGenerator
{
    private const string DirectAttributeMetadataName = "AsyncEventBridge.GenerateAsyncEventsAttribute";
    private const string TargetAttributeMetadataName = "AsyncEventBridge.GenerateAsyncEventsForAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var directlyAnnotatedTypes = context.SyntaxProvider.ForAttributeWithMetadataName(
            DirectAttributeMetadataName,
            static (_, _) => true,
            static (generatorContext, _) => (INamedTypeSymbol)generatorContext.TargetSymbol);

        context.RegisterSourceOutput(directlyAnnotatedTypes, static (productionContext, typeSymbol) =>
        {
            GenerateForType(
                productionContext,
                typeSymbol,
                isExternalTarget: false,
                stopAtTargetTypes: null,
                extensionSuffix: "OccurrenceAsyncEventExtensions");
        });

        context.RegisterSourceOutput(context.CompilationProvider, static (productionContext, compilation) =>
        {
            GenerateAssemblyTargets(productionContext, compilation);
        });
    }

    private static void GenerateAssemblyTargets(
        SourceProductionContext context,
        Compilation compilation)
    {
        var targets = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);

        foreach (var attribute in compilation.Assembly.GetAttributes())
        {
            if (attribute.AttributeClass?.ToDisplayString() != TargetAttributeMetadataName ||
                attribute.ConstructorArguments.Length != 1 ||
                attribute.ConstructorArguments[0].Value is not INamedTypeSymbol requestedType)
            {
                continue;
            }

            var targetType = requestedType.IsUnboundGenericType
                ? requestedType.OriginalDefinition
                : requestedType;

            if (CanGenerateForType(targetType))
            {
                targets.Add(targetType);
            }
        }

        foreach (var typeSymbol in targets)
        {
            var isExternalTarget = !SymbolEqualityComparer.Default.Equals(
                typeSymbol.ContainingAssembly,
                compilation.Assembly);

            if (!isExternalTarget && HasDirectAttribute(typeSymbol))
            {
                continue;
            }

            GenerateForType(
                context,
                typeSymbol,
                isExternalTarget,
                targets,
                extensionSuffix: "TargetedOccurrenceAsyncEventExtensions");
        }
    }

    private static void GenerateForType(
        SourceProductionContext context,
        INamedTypeSymbol typeSymbol,
        bool isExternalTarget,
        HashSet<INamedTypeSymbol>? stopAtTargetTypes,
        string extensionSuffix)
    {
        if (!CanGenerateForType(typeSymbol))
        {
            return;
        }

        var typeParameters = CreateTypeParameterContext(typeSymbol);
        var events = new List<EventGenerationModel>();

        foreach (var eventSymbol in GetEventsForGeneration(
            typeSymbol,
            current =>
                (stopAtTargetTypes is not null && stopAtTargetTypes.Contains(current)) ||
                HasDirectAttribute(current)))
        {
            if (eventSymbol.IsStatic ||
                !CanAccessEvent(eventSymbol, typeSymbol, isExternalTarget))
            {
                continue;
            }

            var shape = EventShapeClassifier.Classify(eventSymbol);

            if (shape.Kind == EventShapeKind.Unsupported ||
                !shape.IsSenderAsyncCompatible ||
                !shape.IsPayloadAsyncCompatible)
            {
                continue;
            }

            events.Add(EventGenerationModel.Create(
                eventSymbol,
                shape,
                typeParameters,
                GetMethodAccessibility(typeSymbol, eventSymbol, requirePublicDelegateParameters: true),
                preserveNullableAnnotations: true));
        }

        if (events.Count == 0)
        {
            return;
        }

        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>")
            .AppendLine("#nullable enable")
            .AppendLine("namespace AsyncEventBridge")
            .AppendLine("{")
            .AppendLine();

        var classAccessibility = events.Any(item => item.Accessibility == "public")
            ? "public"
            : "internal";
        var extensionClassName = GetExtensionClassName(typeSymbol, extensionSuffix);

        source.AppendLine("/// <summary>Contains generated sender-aware async event extension methods.</summary>")
            .Append(classAccessibility)
            .Append(" static class ")
            .Append(extensionClassName)
            .AppendLine()
            .AppendLine("{");

        foreach (var item in events)
        {
            EventOccurrenceEmitter.AppendMethods(source, typeSymbol, item, typeParameters);
        }

        source.AppendLine("}")
            .AppendLine("}");

        context.AddSource(
            extensionClassName + ".g.cs",
            SourceText.From(source.ToString(), Encoding.UTF8));
    }

    private static bool HasDirectAttribute(INamedTypeSymbol typeSymbol) =>
        typeSymbol.GetAttributes().Any(attribute =>
            attribute.AttributeClass?.ToDisplayString() == DirectAttributeMetadataName);

    private static string GetExtensionClassName(INamedTypeSymbol typeSymbol, string suffix)
    {
        var identity = typeSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var builder = new StringBuilder(identity.Length + suffix.Length);

        foreach (var character in identity)
        {
            builder.Append(char.IsLetterOrDigit(character) ? character : '_');
        }

        return builder.Append(suffix).ToString();
    }

}
